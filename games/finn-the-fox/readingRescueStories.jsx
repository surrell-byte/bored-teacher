// HELPER — FIND A STORY BY LEVEL
// ============================================================

export const getReadingRescueStory = (level) => {
  return readingRescueStories.find(
    (story) => story.level === Number(level)
  );
};


// ============================================================
// HELPER — FIND A SPECIFIC PAGE
// ============================================================

export const getReadingRescuePage = (level, page) => {
  const story = getReadingRescueStory(level);

  if (!story) return null;

  return story.pages.find(
    (storyPage) => storyPage.page === Number(page)
  );
};
