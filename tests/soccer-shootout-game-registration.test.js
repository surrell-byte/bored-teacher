const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');

const root = path.resolve(__dirname, '..');

test('Soccer Shootout is registered and uses the supplied stadium background', () => {
  const catalog = fs.readFileSync(path.join(root, 'games/catalog.data.ts'), 'utf8');
  const components = fs.readFileSync(path.join(root, 'games/catalog.components.tsx'), 'utf8');
  const game = fs.readFileSync(path.join(root, 'games/soccer-shootout/SoccerShootout.jsx'), 'utf8');
  const styles = fs.readFileSync(path.join(root, 'games/soccer-shootout/soccerShootout.css'), 'utf8');
  const shell = fs.readFileSync(path.join(root, 'engine/layout/GameShell.tsx'), 'utf8');
  const route = fs.readFileSync(path.join(root, 'app/games/[game]/page.tsx'), 'utf8');
  const globalStyles = fs.readFileSync(path.join(root, 'app/globals.css'), 'utf8');
  const background = path.join(root, 'public/assets/games/soccer-shootout/stadium-background.png');
  const cover = path.join(root, 'public/assets/covers/soccer-shootout-cover.webp');
  const keeperSprites = path.join(root, 'public/assets/games/soccer-shootout/goalkeeper-sprites-v2.png');
  const keeperSaveCenter = path.join(root, 'public/assets/games/soccer-shootout/goalkeeper-save-center.png');
  const keeperDiveLeft = path.join(root, 'public/assets/games/soccer-shootout/goalkeeper-dive-left.png');
  const keeperSaveLeft = path.join(root, 'public/assets/games/soccer-shootout/goalkeeper-save-left.png');
  const keeperAnticipation = path.join(root, 'public/assets/games/soccer-shootout/goalkeeper-anticipation.png');
  const keeperCelebration = path.join(root, 'public/assets/games/soccer-shootout/goalkeeper-celebration.png');
  const keeperDefeated = path.join(root, 'public/assets/games/soccer-shootout/goalkeeper-defeated.png');
  const stadiumPhone = path.join(root, 'public/assets/games/soccer-shootout/stadium-background-phone.png');
  const splashPhone = path.join(root, 'public/assets/games/soccer-shootout/splash-phone.png');
  const splashDesktop = path.join(root, 'public/assets/games/soccer-shootout/splash-desktop.png');
  const overheadBackground = path.join(root, 'public/assets/games/soccer-shootout/overhead-background.png');

  assert.match(catalog, /soccershootout:\s*\{[\s\S]*?name:\s*"Soccer Shootout"[\s\S]*?hasComponent:\s*true/);
  assert.match(components, /soccershootout:\s*lazyGame\('soccershootout',\s*\(\)\s*=>\s*import\('@\/games\/soccer-shootout\/SoccerShootout\.jsx'\)\)/);
  assert.match(styles, /background-image:\s*url\("\/assets\/games\/soccer-shootout\/stadium-background\.png"\)/);
  assert.ok(fs.existsSync(background), 'stadium background asset should be present');
  assert.ok(fs.existsSync(cover), 'game cover should be present');
  assert.ok(fs.existsSync(keeperSprites), 'goalkeeper sprite sheet should be present');
  assert.ok(fs.existsSync(keeperSaveCenter), 'center save sprite should be present');
  assert.ok(fs.existsSync(keeperDiveLeft), 'left dive sprite should be present');
  assert.ok(fs.existsSync(keeperSaveLeft), 'left save sprite should be present');
  assert.ok(fs.existsSync(keeperAnticipation), 'anticipation sprite should be present');
  assert.ok(fs.existsSync(keeperCelebration), 'celebration sprite should be present');
  assert.ok(fs.existsSync(keeperDefeated), 'defeated sprite should be present');
  assert.ok(fs.existsSync(stadiumPhone), 'portrait stadium background should be present');
  assert.ok(fs.existsSync(splashPhone), 'portrait welcome image should be present');
  assert.ok(fs.existsSync(splashDesktop), 'desktop welcome image should be present');
  assert.ok(fs.existsSync(overheadBackground), 'overhead menu background should be present');
  assert.doesNotMatch(styles, /goalkeeper-moves-v3\.png/);
  assert.match(styles, /\.ss-keeper--dive-left,\s*\.ss-keeper--dive-right\s*\{[^}]*goalkeeper-dive-left\.png/);
  assert.match(styles, /\.ss-keeper--save-left\s*\{[^}]*goalkeeper-save-left\.png/);
  assert.match(styles, /\.ss-keeper--save-center\s*\{[^}]*goalkeeper-save-center\.png/);
  assert.match(styles, /\.ss-keeper--save-right\s*\{[^}]*goalkeeper-save-left\.png/);
  assert.match(styles, /\.ss-keeper--ready\s*\{[^}]*goalkeeper-anticipation\.png/);
  assert.match(styles, /\.ss-keeper--celebrate\s*\{[^}]*goalkeeper-celebration\.png/);
  assert.match(styles, /\.ss-keeper--disappointed\s*\{[^}]*goalkeeper-defeated\.png/);
  assert.match(styles, /\.soccer-shootout\.is-setup-screen\s*\{[^}]*overhead-background\.png/);
  assert.match(styles, /@media \(max-width: 760px\) and \(orientation: portrait\)\s*\{[\s\S]*?stadium-background-phone\.png/);
  assert.match(globalStyles, /\.game-shell--soccershootout \.route-game-welcome\.soccer-shootout-route-welcome\s*\{[^}]*splash-desktop\.png/);
  assert.match(globalStyles, /@media \(max-width: 760px\) and \(orientation: portrait\)\s*\{[\s\S]*?splash-phone\.png/);
  assert.match(styles, /@keyframes ss-keeper-jump-right\s*\{[\s\S]*?scaleX\(-1\)/);
  assert.match(styles, /background-size:\s*500%\s+300%/);
  assert.match(styles, /\.soccer-shootout\s*\{[\s\S]*?width:\s*100%;[\s\S]*?height:\s*100%;[\s\S]*?border:\s*0;/);
  assert.match(styles, /border-radius:\s*0;/);
  assert.match(styles, /goalkeeper-sprites-v2\.png/);
  assert.match(game, /ss-keeper--\$\{keeperPose\}/);
  assert.match(game, /setKeeperPose\("ready"\)/);
  assert.match(game, /setKeeperPose\(Math\.max\(\.\.\.nextPlayerGoals\.slice\(0, playerCount\)\) < 3 \? "celebrate" : "disappointed"\)/);
  assert.match(game, /useState\("menu"\)/);
  assert.match(game, /useState\("classic"\)/);
  assert.match(game, /window\.addEventListener\("soccer-shootout:main-menu", handleMainMenu\)/);
  assert.doesNotMatch(game, /className="ss-menu-button"/);
  assert.match(route, /mainMenuInDropdownOnly=\{gameId === 'soccershootout'\}/);
  assert.match(route, /window\.dispatchEvent\(new Event\('soccer-shootout:main-menu'\)\)/);
  assert.match(shell, /!mainMenuInDropdownOnly/);
  assert.match(game, /useState\(1\)/);
  assert.match(game, /const ESL_QUESTIONS = QUIZ_QUESTIONS\.English/);
  assert.match(game, /const maxShots = SHOT_LIMIT \* playerCount/);
  assert.match(game, /const activePlayerIndex = playerCount === 2/);
  assert.match(game, /if \(answer === currentQuestion\.answer\)/);
  assert.match(game, /function shuffledKeeperDirections\(\)\s*\{[\s\S]*?DIRECTIONS\.map/);
  assert.match(game, /keeperChoicesRef\.current = shuffledKeeperDirections\(\)/);
  assert.match(game, /const keeperChoice = keeperChoicesRef\.current\.pop\(\)/);
  assert.doesNotMatch(game, /keeperSheet|keeperFrame|ADDITIONAL_KEEPER_POSES/);
  assert.match(game, /window\.crypto\.getRandomValues\(value\)/);
  assert.match(game, /SHOT_LIMIT = 5/);
  assert.match(game, /onClick=\{shoot\}/);
  assert.match(game, /aria-label="Choose where to aim"/);
  assert.match(game, /left:\s*\{\s*x:\s*"39\.33%",\s*y:\s*"39\.5%"/);
  assert.match(styles, /left:\s*var\(--shot-x\);[\s\S]*?top:\s*var\(--shot-y\);/);
});
